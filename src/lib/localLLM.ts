/**
 * Check if WebGPU is available in current browser
 */
export async function isWebGPUSupported(): Promise<boolean> {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') return false;
  try {
    const nav = navigator as any;
    if (!nav.gpu) return false;
    const adapter = await nav.gpu.requestAdapter();
    return Boolean(adapter);
  } catch {
    return false;
  }
}

/**
 * Initialize and load a local LLM in browser via WebGPU
 */
export async function loadWebLLMModel(
  modelId: string,
  onProgress?: (progressText: string, progressRatio: number) => void
): Promise<any> {
  if (typeof window === 'undefined') return null;

  if (activeEngine && currentLoadedModel === modelId) {
    onProgress?.('Model is ready in memory', 1);
    return activeEngine;
  }

  if (!webLLMModule) {
    webLLMModule = await import('@mlc-ai/web-llm');
  }

  const { CreateMLCEngine } = webLLMModule;

  onProgress?.(`Initializing WebGPU engine for ${modelId}...`, 0.05);

  activeEngine = await CreateMLCEngine(modelId, {
    initProgressCallback: (report) => {
      onProgress?.(report.text, report.progress || 0);
    }
  });

  currentLoadedModel = modelId;
  return activeEngine;
}

/**
 * Generate completion using browser local WebLLM
 */
export async function queryWebLLM(
  systemPrompt: string,
  userPrompt: string,
  modelId: string,
  onProgress?: (text: string, progress: number) => void
): Promise<string> {
  const engine = await loadWebLLMModel(modelId, onProgress);
  if (!engine) throw new Error('WebLLM engine could not be initialized.');

  const messages = [
    { role: 'system', content: systemPrompt },
    { role: 'user', content: userPrompt }
  ];

  const reply = await engine.chat.completions.create({
    messages,
    temperature: 0.3,
    max_tokens: 1500
  });

  return reply.choices[0]?.message?.content || 'No output generated by local model.';
}

/**
 * Query a desktop local Ollama instance (e.g. http://localhost:11434)
 */
export async function queryOllama(
  systemPrompt: string,
  userPrompt: string,
  modelName: string = 'llama3.2',
  endpoint: string = 'http://localhost:11434'
): Promise<string> {
  const cleanUrl = endpoint.replace(/\/+$/, '');
  const url = `${cleanUrl}/api/chat`;

  const payload = {
    model: modelName,
    messages: [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt }
    ],
    stream: false,
    options: {
      temperature: 0.3
    }
  };

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  });

  if (!res.ok) {
    const errText = await res.text().catch(() => '');
    throw new Error(`Ollama error (${res.status}): ${errText || 'Could not communicate with local Ollama server'}`);
  }

  const data = await res.json();
  return data.message?.content || 'No response from local Ollama model.';
}

/**
 * Test Ollama connection
 */
export async function testOllamaConnection(endpoint: string = 'http://localhost:11434'): Promise<{
  ok: boolean;
  models: string[];
  error?: string;
}> {
  try {
    const cleanUrl = endpoint.replace(/\/+$/, '');
    const res = await fetch(`${cleanUrl}/api/tags`, { method: 'GET' });
    if (!res.ok) return { ok: false, models: [], error: `Ollama returned status ${res.status}` };
    const data = await res.json();
    const models = (data.models || []).map((m: any) => m.name || m.model);
    return { ok: true, models };
  } catch (err: any) {
    return { ok: false, models: [], error: err.message || 'Cannot reach localhost:11434' };
  }
}
